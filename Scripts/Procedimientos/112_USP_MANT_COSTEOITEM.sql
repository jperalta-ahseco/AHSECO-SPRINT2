		IF @INDCOSTEADO = 'S' BEGIN
			SELECT @NUM = COUNT(1) FROM TBD_COTIZACIONCOSTOS TX WHERE TX.ID_COTDETALLE IN (SELECT T1.ID FROM TBD_COTIZACIONVENTA T1 WHERE T1.ID_COTIZACION = @IDCOTIZACION) 
			AND (ISNULL(MONTOUNICOSTO,0) <= 0 AND ISNULL(MONTOTOTCOSTO,0) <= 0);
			IF @NUM > 0 BEGIN
