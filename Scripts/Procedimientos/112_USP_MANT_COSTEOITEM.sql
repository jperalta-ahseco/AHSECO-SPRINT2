		--	IF @TOTALCANTCOSTO > 0 BEGIN
		--		SET @FLAG_GARANTADIC = 1;
		--	END
		--END
		
		--
		-- CALIBRACION
		--
		SELECT @TOTALCANTCOSTO = SUM(ISNULL(CANTCOSTO,0)) FROM [dbo].[TBD_COTIZACIONCOSTOS]
		WHERE ID_COTDETALLE = @IDCOTDETALLE AND CODCOSTO = 'CXCD0007' AND (ISNULL(MONTOUNICOSTO,0) > 0 OR ISNULL(MONTOTOTCOSTO,0) > 0);

		IF @TOTALCANTCOSTO = @CANTCOTIZADO BEGIN
			SET @FLAG_CALIB = 2;
		END
		ELSE BEGIN
			IF @TOTALCANTCOSTO > 0 BEGIN
				SET @FLAG_CALIB = 1;
			END
		END
		
		--
		-- FLETE
		--
		SELECT @TOTALCANTCOSTO = SUM(ISNULL(CANTCOSTO,0)) FROM [dbo].[TBD_COTIZACIONCOSTOS]
		WHERE ID_COTDETALLE = @IDCOTDETALLE AND CODCOSTO = 'CXCD0008' AND (ISNULL(MONTOUNICOSTO,0) > 0 OR ISNULL(MONTOTOTCOSTO,0) > 0);

		IF @TOTALCANTCOSTO = @CANTCOTIZADO BEGIN
			SET @FLAG_FLETE = 2;
		END
		ELSE BEGIN
			IF @TOTALCANTCOSTO > 0 BEGIN
				SET @FLAG_FLETE = 1;
			END
		END

		SET @INDCOSTEADO = 'S';

		--
		-- VALIDA que los INDICADORES tengan sus registros de COSTOS respectivos
		--
		IF @INDINFOVIDEO IS NOT NULL BEGIN
			IF ISNULL(@INDINFOVIDEO,'') = 'S' AND ISNULL(@FLAG_VIDEOS,0) = 0 BEGIN
				SET @INDCOSTEADO = 'N'
			END
		END

		IF @INDINFOMANUAL IS NOT NULL BEGIN
			IF ISNULL(@INDINFOMANUAL,'') = 'S' AND ISNULL(@FLAG_MANUALES,0) = 0 BEGIN
				SET @INDCOSTEADO = 'N'
			END
		END

		IF @INDINSTALACION IS NOT NULL BEGIN
			IF ISNULL(@INDINSTALACION,'') = 'S' AND ISNULL(@FLAG_INSTALACION,0) = 0 BEGIN
				SET @INDCOSTEADO = 'N'
			END
		END

		IF @INDCAPACITACION IS NOT NULL BEGIN
			IF ISNULL(@INDCAPACITACION,'') = 'S' AND ISNULL(@FLAG_CAPACITACION,0) = 0 BEGIN
				SET @INDCOSTEADO = 'N'
			END
		END

		--IF @INDGARANADIC IS NOT NULL BEGIN
		--	IF ISNULL(@INDGARANADIC,'') = 'S' AND ISNULL(@FLAG_GARANTADIC,0) = 0 BEGIN
		--		SET @INDCOSTEADO = 'N'
		--	END
		--END

		IF @INDMANTPREVENT IS NOT NULL BEGIN
			IF ISNULL(@INDMANTPREVENT,'') = 'S' AND ISNULL(@FLAG_MANTPREV,0) = 0 BEGIN
				SET @INDCOSTEADO = 'N'
			END
		END

		IF @INDCALIB IS NOT NULL BEGIN
			IF ISNULL(@INDCALIB,'') = 'S' AND ISNULL(@FLAG_CALIB,0) = 0 BEGIN
				SET @INDCOSTEADO = 'N'
			END
		END
		
		IF @INDFLETE IS NOT NULL BEGIN
			IF ISNULL(@INDFLETE,'') = 'S' AND ISNULL(@FLAG_FLETE,0) = 0 BEGIN
				SET @INDCOSTEADO = 'N'
			END
		END
		
		--
		-- VALIDA que los registros de costos hayan sido VALORIZADOS con sus montos respectivos
		--
		IF @INDCOSTEADO = 'S' BEGIN
			SELECT @NUM = COUNT(1) FROM TBD_COTIZACIONCOSTOS TX WHERE TX.ID_COTDETALLE IN (SELECT T1.ID FROM TBD_COTIZACIONVENTA T1 WHERE T1.ID_COTIZACION = @IDCOTIZACION) 
			AND (ISNULL(MONTOUNICOSTO,0) <= 0 AND ISNULL(MONTOTOTCOSTO,0) <= 0);
			IF @NUM > 0 BEGIN
				SET @INDCOSTEADO = 'N';
			END
		END

		UPDATE TBM_COTIZACIONVENTA SET INDCOSTEADO = @INDCOSTEADO WHERE ID_COTIZACION = @IDCOTIZACION;
		
		EXEC USP_UPD_TOTALIZAR_COTDET @IDCOTDETALLE

		
			SET  @CODIGO = 1
		    SET @MSG ='Se realizó la actualización de costeo con éxito'


	END

	SELECT @CODIGO COD ,@MSG MSG
	SET NOCOUNT OFF;
