CREATE OR ALTER PROCEDURE USP_MANT_TBD_DESPACHO_COTIZACION
/*==================================================================================================
	NOMBRE:					FECHA:		DESCRIPCIÓN:
	Diego A. Bazalar		24.02.25	se realiza el mantenimiento de la tabla [TBD_DESPACHO_COTIZACION]
	EXEC USP_MANT_TBD_DESPACHO_COTIZACION
  ==================================================================================================*/
	@IsTipoProceso			CHAR(1)
	,@IsID					BIGINT
	,@IsID_SOLDEPACHO		BIGINT
	,@IsID_COTDETALLE		BIGINT
	,@IsCANTIDAD			INT
	,@IsINDSTOCK			CHAR(1)
	,@IsVALORUNITARIO		DECIMAL(18,9)
	,@IsVALORTOTAL			DECIMAL(18,9)
	,@IsMARGENADICIONAL		DECIMAL(18,9)
	,@IsVVTOTALSIGVCGAN		DECIMAL(18,9)
	,@IsMONTODSCTO			DECIMAL(18,9)
	,@IsVVTOTALSIGVDSCTO	DECIMAL(18,9)
	,@IsPorcentajeDscto		DECIMAL(18,9)
	,@IsUsrEjecuta			VARCHAR(50)
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE @CODIGO INT, @MSG VARCHAR(200)

	IF(@IsTipoProceso = 'I')
	BEGIN
		
		DECLARE @MONTOTOTALCOSTOS DECIMAL(18,9) , @IsANTVALORTOTAL DECIMAL(18,9)

		--Se obtiene el monto total del costeo ya que se utilizará como base para calcular el siguiente costeo
		SELECT @MONTOTOTALCOSTOS = SUM(MONTOTOTCOSTO) FROM [dbo].[TBD_COTIZACIONCOSTOS] WHERE ID_COTDETALLE = @IsID_COTDETALLE AND ISNULL(ELIMINADO, 0) != 1

		SELECT @IsVALORUNITARIO = ((CANTIDAD * VVENTAUNI) +  ISNULL(@MONTOTOTALCOSTOS,0)) / CANTIDAD FROM [dbo].[TBD_COTIZACIONVENTA] WHERE ID = @IsID_COTDETALLE
 
		--El anterior valor total equivale a la suma del valor total(cantidad x ventauni) más la suma de todos los costos
		--SET @IsANTVALORTOTAL= @IsANTVALORTOTAL + @MONTOTOTALCOSTOS

		--Se calcula el nuevo valor unitario
		--SET @IsVALORUNITARIO = @IsANTVALORTOTAL	/ (SELECT TOP 1 CANTIDAD FROM [dbo].[TBD_COTIZACIONVENTA] WHERE ID = @IsID_COTDETALLE)


		--Se calcula el nuevo valor total 
		SET @IsVALORTOTAL = ISNULL(@IsVALORUNITARIO,0) * ISNULL(@IsCANTIDAD,0)

		IF(ISNULL(@IsMARGENADICIONAL, 0) > 0)
		BEGIN
			SET @IsVVTOTALSIGVCGAN =  @IsVALORTOTAL + (@IsVALORTOTAL * (@IsMARGENADICIONAL / 100))
		END

		IF(ISNULL(@IsPorcentajeDscto,0) > 0)
		BEGIN
			SET @IsMONTODSCTO = ISNULL(@IsVVTOTALSIGVCGAN, @IsVALORTOTAL) * (@IsPorcentajeDscto / 100 ) --Se calcula el monto de descuento.
			SET @IsVVTOTALSIGVDSCTO = CASE WHEN @IsMARGENADICIONAL > 0 THEN @IsVVTOTALSIGVCGAN - @IsMONTODSCTO
										ELSE @IsVALORTOTAL - @IsMONTODSCTO END
		END

		INSERT INTO [dbo].[TBD_DESPACHO_COTIZACION](ID_SOLDESPACHO,ID_COTDETALLE,CANTIDAD, INDSTOCK, VALORUNITARIO,VALORTOTAL,MARGENADICIONAL,VVTOTALSIGVCGAN,MONTODSCTO,VVTOTALSIGVDSCTO,USR_REG,FEC_REG)
		VALUES (@IsID_SOLDEPACHO,@IsID_COTDETALLE,@IsCANTIDAD, @IsINDSTOCK, @IsVALORUNITARIO,@IsVALORTOTAL,@IsMARGENADICIONAL,@IsVVTOTALSIGVCGAN,@IsMONTODSCTO,@IsVVTOTALSIGVDSCTO,@IsUsrEjecuta,GETDATE())

		IF(@@ROWCOUNT = 0)
		BEGIN
			SET @CODIGO = 0
			SET @MSG = 'Se produjo un problema al realizar la inserción en la tabla [[TBD_DESPACHO_COTIZACION]]'
		END
		ELSE
		BEGIN

			SET @CODIGO = @@IDENTITY
			SET @MSG = 'Se insertó en la tabla [[TBD_DESPACHO_COTIZACION]]' 
		END
	END
	IF(@IsTipoProceso = 'U')
	BEGIN
		UPDATE [dbo].[TBD_DESPACHO_COTIZACION]
		SET	
		ID_SOLDESPACHO		= @IsID_SOLDEPACHO	
		,ID_COTDETALLE		= @IsID_COTDETALLE	
		,CANTIDAD			= @IsCANTIDAD		
		,VALORUNITARIO		= @IsVALORUNITARIO	
		,VALORTOTAL			= @IsVALORTOTAL		
		,MARGENADICIONAL	= @IsMARGENADICIONAL	
		,VVTOTALSIGVCGAN	= @IsVVTOTALSIGVCGAN	
		,MONTODSCTO			= @IsMONTODSCTO		
		,VVTOTALSIGVDSCTO	= @IsVVTOTALSIGVDSCTO
		,USR_MOD			= @IsUsrEjecuta		
		,FEC_MOD			= GETDATE()
		WHERE ID = @IsID

		IF(@@ROWCOUNT = 0)
		BEGIN
			SET @CODIGO = 0
			SET @MSG = 'Ocurrió un error al actualizar la tabla [[TBD_DESPACHO_COTIZACION]]'
		END
		ELSE
		BEGIN
			SET @CODIGO = @IsID
			SET @MSG = 'Se realizó la actualización de la tabla [[TBD_DESPACHO_COTIZACION]]'
		END
	END

	SELECT @CODIGO COD ,@MSG MSG
	SET NOCOUNT OFF;

END